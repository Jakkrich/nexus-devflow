import { createHash } from "node:crypto";

export const OVERVIEW_MAX_BYTES = 20_000;

export type PlanningValidationCode =
  | "placeholder_project_plan"
  | "placeholder_build_plan"
  | "empty_build_checklist"
  | "stub_build_plan_mismatch";

export interface PlanningValidationIssue {
  readonly code: PlanningValidationCode;
  readonly file: "devflow/project-plan.md" | "devflow/build-plan.md";
  readonly message: string;
  readonly remediation: string;
}

export interface PlanningValidationResult {
  readonly valid: boolean;
  readonly activeChecklistCount: number;
  readonly issues: PlanningValidationIssue[];
}

export type OverviewFreshnessStatus =
  | "fresh"
  | "uncompiled_stub"
  | "oversized"
  | "placeholder_leak"
  | "missing_hash"
  | "stale_hash";

export interface OverviewFreshnessResult {
  readonly ok: boolean;
  readonly status: OverviewFreshnessStatus;
  readonly bytes: number;
  readonly maxBytes: number;
  readonly recordedHash: string | null;
  readonly expectedHash: string | null;
  readonly message: string;
}

export interface InspectOverviewFreshnessOptions {
  readonly overviewContent: string;
  readonly projectPlanContent: string | null;
  readonly buildPlanContent: string | null;
  readonly maxBytes?: number;
}

const SOURCE_HASH_PATTERN = /<!--\s*devflow:source-hash\s+([0-9a-f]{64})\s*-->/i;
const COMPILED_OVERVIEW_MARKERS = [
  "devflow:source-hash",
  "Living context artifact generated by `scripts/overview.ts`",
  "## 5. Upcoming Build Queue",
  "## 9. Verified Developer Commands"
];

const PROJECT_PLAN_PLACEHOLDER_MARKERS = [
  "[ระบุปัญหาหลักที่ผู้ใช้กำลังเผชิญ",
  "[ระบุเป้าหมายหลักของระบบ",
  "[เช่น Solo Developers",
  "[คำอธิบายสั้นๆ เกี่ยวกับสิ่งที่ฟีเจอร์นี้ทำ]",
  "A description of the project and the core problem it solves.",
  "Who will use this system and why.",
  "Primary language, framework, and runtime (e.g. Node.js, Next.js"
];

const BUILD_PLAN_PLACEHOLDER_MARKERS = [
  "สร้าง Data Models, Schemas (Zod) และ Database Migrations เบื้องต้น",
  "วางโครงสร้างหน้าจอหลัก, Navigation Shell และ Design Tokens",
  "[เช่น ใช้ Full Puppeteer",
  "**1. Project Baseline & Context Setup**",
  "**2. Core Data Models & Store**"
];

const LEGACY_FEATURE_STUB_PATTERN = /^[ \t]*-\s*\[[ xX]\][ \t]+feature\s+(?:one|two)\s*$/im;

const OVERVIEW_LEAK_MARKERS = [
  "TODO: แผนยังคงเป็นแผนต้นแบบ",
  "[ระบุปัญหาหลักที่ผู้ใช้กำลังเผชิญ",
  "[คำอธิบายสั้นๆ เกี่ยวกับสิ่งที่ฟีเจอร์นี้ทำ]",
  "A description of the project and the core problem it solves."
];

function stripHtmlComments(markdown: string): string {
  return markdown.replace(/<!--[\s\S]*?-->/g, "");
}

function isMinimalStubText(markdown: string): boolean {
  const cleaned = stripHtmlComments(markdown)
    .replace(/^#.*$/gm, "")
    .replace(/^>.*$/gm, "")
    .replace(/^[-*_\s]+$/gm, "")
    .trim();
  return cleaned.length < 15 || /^stub$/i.test(cleaned);
}

/**
 * Extract active `- [ ]` / `- [x]` items outside Later / Post-MVP sections.
 */
export function extractActiveBuildChecklistItems(buildPlanContent: string): string[] {
  const lines = stripHtmlComments(buildPlanContent).split(/\r?\n/);
  const items: string[] = [];
  let laterHeadingLevel: number | null = null;

  for (const line of lines) {
    const headingMatch = /^(#{1,6})\s+(.*)$/.exec(line.trim());
    if (headingMatch) {
      const level = headingMatch[1].length;
      const heading = headingMatch[2].toLowerCase();
      if (laterHeadingLevel !== null && level > laterHeadingLevel) {
        continue;
      }
      laterHeadingLevel = /\b(?:later|post-mvp)\b/i.test(heading) ? level : null;
      continue;
    }
    if (laterHeadingLevel !== null) {
      continue;
    }
    const itemMatch = /^[ \t]*-\s*\[[ xX]\][ \t]+(.+?)\s*$/.exec(line);
    if (itemMatch?.[1]) {
      items.push(itemMatch[1]);
    }
  }

  return items;
}

/**
 * Normalize only checked build-plan markers (`- [x]` / `- [X]`) to `- [ ]`
 * while preserving indentation, newlines, and all other bytes.
 */
export function normalizeBuildPlanForHash(buildPlanContent: string): string {
  return buildPlanContent.replace(/^([ \t]*-[ \t]*)\[[xX]\]/gm, "$1[ ]");
}

/**
 * Compute deterministic SHA-256 over project-plan.md + 0x00 + normalized build-plan.md.
 */
export function computeOverviewSourceHash(
  projectPlanContent: string,
  buildPlanContent: string
): string {
  const normalizedBuild = normalizeBuildPlanForHash(buildPlanContent);
  const payload = Buffer.concat([
    Buffer.from(projectPlanContent, "utf8"),
    Buffer.from([0]),
    Buffer.from(normalizedBuild, "utf8")
  ]);
  return createHash("sha256").update(payload).digest("hex");
}

/**
 * Extract embedded `<!-- devflow:source-hash <64-hex> -->` fingerprint.
 */
export function extractOverviewSourceHash(overviewContent: string): string | null {
  const match = SOURCE_HASH_PATTERN.exec(overviewContent);
  return match?.[1]?.toLowerCase() ?? null;
}

export function validatePlanningInputs(
  projectPlanContent: string,
  buildPlanContent: string
): PlanningValidationResult {
  const issues: PlanningValidationIssue[] = [];
  const projectStripped = stripHtmlComments(projectPlanContent);
  const buildStripped = stripHtmlComments(buildPlanContent);

  const projectHasPlaceholder =
    isMinimalStubText(projectPlanContent) ||
    PROJECT_PLAN_PLACEHOLDER_MARKERS.some((marker) => projectStripped.includes(marker));

  if (projectHasPlaceholder) {
    issues.push({
      code: "placeholder_project_plan",
      file: "devflow/project-plan.md",
      message: "devflow/project-plan.md ยังมีข้อความแม่แบบ (placeholder) หรือยังไม่ได้กรอกข้อมูลจริงของโปรเจกต์",
      remediation: "แก้ไข devflow/project-plan.md ให้เป็นวิสัยทัศน์ สถาปัตยกรรม และข้อกำหนดจริง แล้วรัน '/overview' ใหม่"
    });
  }

  const activeItems = extractActiveBuildChecklistItems(buildPlanContent);
  const buildHasPlaceholder =
    (activeItems.length === 0 && isMinimalStubText(buildPlanContent)) ||
    LEGACY_FEATURE_STUB_PATTERN.test(buildStripped) ||
    BUILD_PLAN_PLACEHOLDER_MARKERS.some((marker) => buildStripped.toLowerCase().includes(marker.toLowerCase()));

  if (!projectHasPlaceholder && (buildHasPlaceholder || activeItems.length === 0)) {
    issues.push({
      code: "stub_build_plan_mismatch",
      file: "devflow/build-plan.md",
      message: "devflow/project-plan.md มีแผนจริงแล้ว แต่ devflow/build-plan.md ยังเป็นแม่แบบ stub หรือไม่มีรายการ checklist พร้อมส่งมอบ",
      remediation: "แทนที่รายการตัวอย่างใน devflow/build-plan.md ด้วยฟีเจอร์จริงในรูปแบบ `- [ ] N. ชื่อฟีเจอร์` (นอกหัวข้อ Later) แล้วรัน '/overview' ใหม่"
    });
  }

  if (buildHasPlaceholder) {
    issues.push({
      code: "placeholder_build_plan",
      file: "devflow/build-plan.md",
      message: "devflow/build-plan.md ยังมีรายการตัวอย่างจาก template หรือ stub ตกค้างอยู่",
      remediation: "ลบหรือเขียนทับรายการตัวอย่างใน devflow/build-plan.md ด้วยงานจริงของโปรเจกต์ แล้วรัน '/overview' ใหม่"
    });
  }

  if (activeItems.length === 0) {
    issues.push({
      code: "empty_build_checklist",
      file: "devflow/build-plan.md",
      message: "devflow/build-plan.md ไม่มีรายการ checkbox (`- [ ]` / `- [x]`) ในขอบเขตหลักที่จะนำไปคอมไพล์",
      remediation: "เพิ่มรายการฟีเจอร์อย่างน้อย 1 ข้อในรูปแบบ `- [ ] 1. **ชื่อฟีเจอร์** - คำอธิบาย` ใน devflow/build-plan.md"
    });
  }

  return {
    valid: issues.length === 0,
    activeChecklistCount: activeItems.length,
    issues
  };
}

function hashesMatchAcrossLineEndings(
  recordedHash: string,
  projectPlanContent: string,
  buildPlanContent: string
): boolean {
  if (computeOverviewSourceHash(projectPlanContent, buildPlanContent) === recordedHash) {
    return true;
  }
  const lfProject = projectPlanContent.replace(/\r\n/g, "\n");
  const lfBuild = buildPlanContent.replace(/\r\n/g, "\n");
  if (computeOverviewSourceHash(lfProject, lfBuild) === recordedHash) {
    return true;
  }
  const crlfProject = lfProject.replace(/\n/g, "\r\n");
  const crlfBuild = lfBuild.replace(/\n/g, "\r\n");
  return computeOverviewSourceHash(crlfProject, crlfBuild) === recordedHash;
}

export function inspectOverviewFreshness(
  options: InspectOverviewFreshnessOptions
): OverviewFreshnessResult {
  const maxBytes = options.maxBytes ?? OVERVIEW_MAX_BYTES;
  const bytes = Buffer.byteLength(options.overviewContent, "utf8");
  const recordedHash = extractOverviewSourceHash(options.overviewContent);
  const expectedHash =
    options.projectPlanContent !== null && options.buildPlanContent !== null
      ? computeOverviewSourceHash(options.projectPlanContent, options.buildPlanContent)
      : null;

  if (bytes >= maxBytes) {
    return {
      ok: false,
      status: "oversized",
      bytes,
      maxBytes,
      recordedHash,
      expectedHash,
      message: `devflow/context/project-overview.md is oversized (${bytes} bytes >= ${maxBytes} bytes). Run '/overview' to regenerate a compact overview.`
    };
  }

  const looksCompiled =
    recordedHash !== null ||
    COMPILED_OVERVIEW_MARKERS.some((marker) => options.overviewContent.includes(marker));

  if (!looksCompiled) {
    return {
      ok: true,
      status: "uncompiled_stub",
      bytes,
      maxBytes,
      recordedHash: null,
      expectedHash,
      message: `devflow/context/project-overview.md is an uncompiled starter stub (${bytes} bytes).`
    };
  }

  if (OVERVIEW_LEAK_MARKERS.some((marker) => options.overviewContent.includes(marker))) {
    return {
      ok: false,
      status: "placeholder_leak",
      bytes,
      maxBytes,
      recordedHash,
      expectedHash,
      message: "devflow/context/project-overview.md contains template placeholder text. Fill project-plan.md/build-plan.md and regenerate via '/overview'."
    };
  }

  if (!recordedHash) {
    return {
      ok: false,
      status: "missing_hash",
      bytes,
      maxBytes,
      recordedHash: null,
      expectedHash,
      message: "devflow/context/project-overview.md is missing its devflow:source-hash fingerprint. Run '/overview' to stamp it."
    };
  }

  if (
    options.projectPlanContent !== null &&
    options.buildPlanContent !== null &&
    !hashesMatchAcrossLineEndings(recordedHash, options.projectPlanContent, options.buildPlanContent)
  ) {
    return {
      ok: false,
      status: "stale_hash",
      bytes,
      maxBytes,
      recordedHash,
      expectedHash,
      message: `devflow/context/project-overview.md is out of date with planning docs (recorded hash ${recordedHash.slice(0, 12)} != expected ${expectedHash?.slice(0, 12)}). Run '/overview'.`
    };
  }

  return {
    ok: true,
    status: "fresh",
    bytes,
    maxBytes,
    recordedHash,
    expectedHash,
    message: `devflow/context/project-overview.md is fresh and within budget (${bytes} < ${maxBytes} bytes).`
  };
}
